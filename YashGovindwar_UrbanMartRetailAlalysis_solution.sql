-- 1.Ranking products within each category by total revenue generated.

SELECT p.category, p.product_name, SUM(s.net_amount) as total_revenue, 
       DENSE_RANK() OVER(
						 PARTITION BY p.category
                         ORDER BY SUM(s.net_amount) DESC) AS revenue_rank
FROM products p INNER JOIN sales_transaction s 
ON p.product_id = s.product_id
GROUP BY p.category, p.product_name 
ORDER BY P.CATEGORY, total_revenue DESC;


