-- 5.Month-over-month revenue growth percentage using.

WITH monthly_sales_dif AS
(SELECT MONTH(sale_date) AS month_no, MONTHNAME(sale_date) AS month_name,
       SUM(net_amount) AS current_month_sales,
       LAG(SUM(net_amount)) 
       OVER(
			ORDER BY MONTH(SALE_DATE)
			) AS last_month_sales
FROM sales_transaction
GROUP BY month_no, month_name
ORDER BY month_no)
SELECT *, ((current_month_sales - last_month_sales)/ last_month_sales * 100)
AS monthly_growth_percentage  
FROM monthly_sales_dif ;


-- 6.Products where current stock_quantity is below reorder_level, 
-- and ranking them by restock priority based on how frequently they have sold.

SELECT s.product_id, p.product_name,
       p.stock_quantity, p.reorder_level, 
       SUM(s.quantity) as sold_quantity, 
       DENSE_RANK() OVER(
						 ORDER BY SUM(s.quantity) DESC
                         ) AS restock_priority
FROM sales_transaction s INNER JOIN products p
ON s.product_id = p.product_id  
GROUP BY s.product_id,p.product_name,
         p.stock_quantity,p.reorder_level
HAVING p.stock_quantity < p.reorder_level;    

SELECT 
    p.product_id,
    p.product_name,
    p.stock_quantity,
    p.reorder_level,
    COALESCE(s.sold_quantity, 0) AS sold_quantity,
    DENSE_RANK() OVER (
    ORDER BY COALESCE(s.sold_quantity, 0) DESC
    ) AS restock_priority
FROM products p
LEFT JOIN (
SELECT product_id,
           SUM(quantity) AS sold_quantity
FROM sales_transaction
GROUP BY product_id
) s
ON p.product_id = s.product_id
WHERE p.stock_quantity < p.reorder_level
ORDER BY restock_priority;     


-- 7.Segment customers into 'High', 'Medium' and 'Low' value tiers 
-- based on total spend and count of customers per tier.

WITH per_customer_revenue AS  
(
SELECT customer_id, customer_name, 
       SUM(net_amount) AS total_spend
FROM sales_transaction
GROUP BY customer_id, customer_name
ORDER BY SUM(net_amount) DESC
),
customer_tire_by_spending AS 
(
SELECT customer_id, customer_name, total_spend, 
       (CASE 
             WHEN total_spend <= 30000 then "low" 
             WHEN total_spend < 70000 THEN "medium" 
             WHEN total_spend >= 70000 THEN "high" 
	    END ) AS customer_tire 
FROM per_customer_revenue
)
SELECT customer_tire, COUNT(customer_tire)
FROM customer_tire_by_spending
GROUP BY customer_tire ;

-- 8.Comparision of average monthly revenue during the festive period (October–December) 
-- against the rest of the year, for each store city.

WITH monthly_total_sales AS 
(
SELECT store_city, MONTH(sale_date) AS month_no,
       MONTHNAME(sale_date) AS month_name,
	   SUM(net_amount) AS total_sales
FROM sales_transaction
GROUP BY store_city, month_no, month_name
ORDER BY store_city
)
SELECT store_city,
       ROUND(AVG (CASE WHEN month_no BETWEEN 10 AND 12
       THEN total_sales END),2) AS festive_season_sales, 
	   
       ROUND(AVG (CASE WHEN month_no BETWEEN 1 AND 9
       THEN total_sales END),2) AS non_festive_season_sales,
       
       (ROUND(AVG (CASE WHEN month_no BETWEEN 10 AND 12
       THEN total_sales END),2)
       -
       ROUND(AVG (CASE WHEN month_no BETWEEN 1 AND 9
       THEN total_sales END),2)) AS revenue_diffrence
FROM monthly_total_sales
GROUP BY store_city
ORDER BY REVENUE_DIFFRENCE DESC;
       

-- 9.The best-selling month of the year by revenue.

WITH monthly_sales_ranking AS 
(
SELECT p.category, MONTH(s.sale_date) AS month_no, 
       MONTHNAME(s.sale_date) AS best_performing_month, 
       SUM(s.net_amount) as total_sales,
       ROW_NUMBER() OVER(
                         PARTITION BY p.category
                         ORDER BY SUM(s.net_amount) DESC) AS sales_rank
FROM products p LEFT JOIN sales_transaction s  
ON p.product_id = s.product_id
GROUP BY P.CATEGORY, month_no, best_performing_month
ORDER BY p.category
)
SELECT * FROM monthly_sales_ranking
WHERE sales_rank = 1;

-- 10.Percentage of total revenue contributed by Pune and Mumbai together.

SELECT SUM(CASE
            WHEN store_city IN ('Pune', 'Mumbai')
            THEN net_amount
            ELSE 0
        END) AS pune_mumbai_revenue,
       SUM(net_amount) AS total_revenue,
       ROUND(SUM(CASE
                WHEN store_city IN ('Pune', 'Mumbai')
                THEN net_amount
                ELSE 0
            END) * 100.0 / SUM(net_amount), 2) 
            AS revenue_contribution_pct
FROM sales_transaction ;


-- 11.List of products below their reorder level and rank them by sales velocity.

SELECT p.product_id,
       p.product_name,
       p.category,
       p.stock_quantity,
       p.reorder_level,
       COALESCE(s.sold_quantity, 0) AS sold_quantity,
DENSE_RANK() OVER (
                   ORDER BY COALESCE(s.sold_quantity, 0) DESC
    ) AS restock_priority
FROM products p LEFT JOIN 
    ( SELECT product_id,
             SUM(quantity) AS sold_quantity
    FROM sales_transaction
    GROUP BY product_id) s
    ON p.product_id = s.product_id
WHERE p.stock_quantity < p.reorder_level
ORDER BY restock_priority;
